/** 最近使用在本地存储里的键。 */
const RECENT_KEY = 'e2echo-recent-emojis'

/** 最近使用最多记多少个。 */
const RECENT_MAX = 24

/**
 * 读取最近使用的表情。
 *
 * <p>存储不可用（隐私模式、被禁用等）或内容被改坏时都按“没有记录”处理，不影响正常选表情。</p>
 *
 * @returns 最近使用的表情，最近的在前
 */
export function loadRecentEmojis(): string[] {
  try {
    const raw = window.localStorage.getItem(RECENT_KEY)
    if (!raw) {
      return []
    }
    const parsed = JSON.parse(raw) as unknown
    if (!Array.isArray(parsed)) {
      return []
    }
    return parsed
      .filter((item): item is string => typeof item === 'string')
      .slice(0, RECENT_MAX)
  } catch {
    return []
  }
}

/**
 * 记录一次使用：放到最前面、去重、超出上限的丢掉。
 *
 * @param emoji 刚使用的表情
 * @returns 更新后的最近使用
 */
export function pushRecentEmoji(emoji: string): string[] {
  const list = [emoji, ...loadRecentEmojis().filter((item) => item !== emoji)].slice(0, RECENT_MAX)
  try {
    window.localStorage.setItem(RECENT_KEY, JSON.stringify(list))
  } catch {
    // 写不进去只影响下次记忆，本次插入照常
  }
  return list
}
